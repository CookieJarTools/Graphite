const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  onState: (cb) => ipcRenderer.on('state', (_e, s) => cb(s)),
  onIcon: (cb) => ipcRenderer.on('icon', (_e, i) => cb(i)),
  onShown: (cb) => ipcRenderer.on('shown', (_e, mode) => cb(mode)),
  onReset: (cb) => ipcRenderer.on('reset', () => cb()),
  onIntro: (cb) => ipcRenderer.on('intro', () => cb()),
  requestState: () => ipcRenderer.send('request-state'),
  launch: (id) => ipcRenderer.send('launch', id),
  contextMenu: (id) => ipcRenderer.send('context-menu', id),
  power: (action) => ipcRenderer.send('power', action),
  openPath: (p) => ipcRenderer.send('open-path', p),
  launchAdmin: (id) => ipcRenderer.send('launch-admin', id),
  command: (name) => ipcRenderer.send('command', name),
  webSearch: (query) => ipcRenderer.send('web-search', query),
  hide: () => ipcRenderer.send('hide'),
  // Dev mode only (ignored otherwise): poke the helper, open previews, show a toast, quit.
  devHelper: (line) => ipcRenderer.send('dev-helper', line),
  devPreview: (name) => ipcRenderer.send('dev-preview', name),
  devToast: (message) => ipcRenderer.send('dev-toast', message),
  devQuit: () => ipcRenderer.send('dev-quit'),
  devTaskbarAutoHide: (on) => ipcRenderer.send('dev-taskbar-autohide', on),
  // Files
  files: {
    list: (folder) => ipcRenderer.invoke('files:list', folder),
    count: (folder) => ipcRenderer.invoke('files:count', folder),
    sidebar: () => ipcRenderer.invoke('files:sidebar'),
    settings: () => ipcRenderer.invoke('files:settings'),
    setDensity: (density) => ipcRenderer.send('files:density', density),
    open: (filePath) => ipcRenderer.send('files:open', filePath),
    reveal: (filePath) => ipcRenderer.send('files:reveal', filePath),
    copyPath: (filePath) => ipcRenderer.send('files:copy-path', filePath),
    newWindow: (folder) => ipcRenderer.send('files:new-window', folder),
    trash: (paths) => ipcRenderer.invoke('files:trash', paths),
    rename: (from, newName) => ipcRenderer.invoke('files:rename', from, newName),
    mkdir: (folder) => ipcRenderer.invoke('files:mkdir', folder),
    paste: (mode, sources, destination) => ipcRenderer.invoke('files:paste', mode, sources, destination),
    drag: (paths) => ipcRenderer.send('files:drag', paths),
    window: (action) => ipcRenderer.send('files:window', action),
    menu: (state) => ipcRenderer.send('files:menu', state),
    setClipboard: (mode, paths) => ipcRenderer.send('files:set-clipboard', mode, paths),
    onContextMenu: (cb) => ipcRenderer.on('files-context-menu', (_e, menu) => cb(menu)),
    menuDone: (session, id) => ipcRenderer.send('files:menu-done', session, id),
    onMenu: (cb) => ipcRenderer.on('files-menu', (_e, action) => cb(action)),
    tabDrag: (drag) => ipcRenderer.send('files:tab-drag', drag),
    tabDrop: (drop) => ipcRenderer.invoke('files:tab-drop', drop),
    exportedTabs: (tabs) => ipcRenderer.send('files:exported-tabs', tabs),
    onDropSlot: (cb) => ipcRenderer.on('files-drop-slot', (_e, title) => cb(title)),
    onAdoptTab: (cb) => ipcRenderer.on('files-adopt-tab', (_e, tab) => cb(tab)),
    onExportTabs: (cb) => ipcRenderer.on('files-export-tabs', () => cb()),
    onGhost: (cb) => ipcRenderer.on('files-ghost', (_e, title) => cb(title)),
    onGhostHidden: (cb) => ipcRenderer.on('files-ghost-hidden', () => cb()),
  },
  reportAliases: (aliases) => ipcRenderer.send('aliases', aliases),
  // Switcher
  onSwitcherState: (cb) => ipcRenderer.on('switcher-state', (_e, s) => cb(s)),
  onSwitcherSelect: (cb) => ipcRenderer.on('switcher-select', (_e, i) => cb(i)),
  onSwitcherReset: (cb) => ipcRenderer.on('switcher-reset', () => cb()),
  switcherLayout: (slots) => ipcRenderer.send('switcher-layout', slots),
  switcherPick: (index) => ipcRenderer.send('switcher-pick', index),
  switcherCancel: () => ipcRenderer.send('switcher-cancel'),
  // Tab strips
  onStripState: (cb) => ipcRenderer.on('strip-state', (_e, s) => cb(s)),
  onStripSlot: (cb) => ipcRenderer.on('strip-slot', (_e, s) => cb(s)),
  tabActivate: (hwnd) => ipcRenderer.send('tab-activate', hwnd),
  tabClose: (hwnd) => ipcRenderer.send('tab-close', hwnd),
  tabSplit: (hwnd) => ipcRenderer.send('tab-split', hwnd),
  stripDrag: (hwnd) => ipcRenderer.send('strip-drag', hwnd),
  // The parts of this window that take the mouse (rects in page pixels), or 'capture'
  // while a drag or a rename needs it everywhere. Elsewhere clicks pass through.
  setHitRegions: (rects) => ipcRenderer.send('hit-regions', rects),

  // Quick settings and calendar panels (taskbar)
  openPanel: (kind) => ipcRenderer.send('panel-open', kind),
  closePanel: () => ipcRenderer.send('panel-close'),
  onPanel: (cb) => ipcRenderer.on('panel', (_e, panel) => cb(panel)),
  onSystemState: (cb) => ipcRenderer.on('system-state', (_e, state) => cb(state)),
  onNetworkState: (cb) => ipcRenderer.on('network-state', (_e, wifi) => cb(wifi)),
  systemSet: (command) => ipcRenderer.send('system-set', command),
  openSettings: (page) => ipcRenderer.send('open-settings', page),
  clearNotifications: () => ipcRenderer.send('clear-notifications'),
  onWindowsNotifications: (cb) => ipcRenderer.on('windows-notifications', (_e, items) => cb(items)),
  dismissNotification: (source, id) => ipcRenderer.send('notification-dismiss', source, id),
  openNotificationApp: (appId) => ipcRenderer.send('notification-open', appId),
  onTrayIcons: (cb) => ipcRenderer.on('tray-icons', (_e, icons) => cb(icons)),

  // Settings window
  settings: {
    get: () => ipcRenderer.invoke('settings:get'),
    set: (id, value) => ipcRenderer.send('settings:set', id, value),
    onChanged: (cb) => ipcRenderer.on('settings-changed', (_e, model) => cb(model)),
    window: (action) => ipcRenderer.send('settings:window', action),
    quit: () => ipcRenderer.send('settings:quit'),
  },
  trayClick: (id, button, x, y) => ipcRenderer.send('tray-click', id, button, x, y),
  createTag: (hwnd, name, color) => ipcRenderer.send('tag-create', hwnd, name, color),
  // Toasts
  onToast: (cb) => ipcRenderer.on('toast', (_e, message) => cb(message)),
  toastAction: (id) => ipcRenderer.send('toast-action', id),
  toastEmpty: () => ipcRenderer.send('toast-empty'),
  // Taskbar
  onTaskbarState: (cb) => ipcRenderer.on('taskbar-state', (_e, s) => cb(s)),
  onTaskbarHidden: (cb) => ipcRenderer.on('taskbar-hidden', (_e, hidden) => cb(hidden)),
  taskbarClick: (hwnd) => ipcRenderer.send('taskbar-click', hwnd),
  taskbarContext: (hwnd) => ipcRenderer.send('taskbar-context', hwnd),
  taskbarHome: () => ipcRenderer.send('taskbar-home'),
  taskbarKey: (letter) => ipcRenderer.send('taskbar-key', letter),
  taskbarPeek: () => ipcRenderer.send('taskbar-peek'),
  taskbarLaunch: (key) => ipcRenderer.send('taskbar-launch', key),
  taskbarReorder: (refs) => ipcRenderer.send('taskbar-reorder', refs),
  taskbarMerge: (sourceRef, targetRef) => ipcRenderer.send('taskbar-merge', sourceRef, targetRef),
  taskbarRename: (id, name) => ipcRenderer.send('taskbar-rename', id, name),
  taskbarPreview: (slots) => ipcRenderer.send('taskbar-preview', slots),
  taskbarCursor: () => ipcRenderer.invoke('taskbar-cursor'),
  onTaskbarRename: (cb) => ipcRenderer.on('taskbar-rename', (_e, id) => cb(id)),
});
